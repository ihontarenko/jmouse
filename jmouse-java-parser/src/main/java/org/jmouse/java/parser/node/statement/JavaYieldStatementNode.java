package org.jmouse.java.parser.node.statement;

import org.jmouse.el.node.ChildRole;
import org.jmouse.el.node.NodeKind;
import org.jmouse.el.node.NodeSchema;
import org.jmouse.java.parser.node.expression.JavaExpressionNode;
import org.jmouse.java.parser.node.JavaChildRoleNames;
import org.jmouse.java.parser.node.JavaNodeKindNames;
import org.jmouse.java.parser.source.SourceSpan;

/** Typed yield-statement syntax, with role-owned children in source order. */
public final class JavaYieldStatementNode extends JavaStatementNode {
    public static final NodeKind<JavaYieldStatementNode> KIND = new NodeKind<>(JavaNodeKindNames.YIELD_STATEMENT, JavaYieldStatementNode.class);
    public static final ChildRole<JavaExpressionNode> EXPRESSION = ChildRole.required(JavaChildRoleNames.EXPRESSION, JavaExpressionNode.class);
    public static final NodeSchema<JavaYieldStatementNode> SCHEMA = NodeSchema.of(KIND, EXPRESSION);

    public JavaYieldStatementNode(String sourceName, SourceSpan span) {
        super(SCHEMA, sourceName, span);
    }

    public JavaExpressionNode expression() {
        return child(EXPRESSION);
    }

    public void setExpression(JavaExpressionNode node) {
        setChild(EXPRESSION, node);
    }
}

