package org.jmouse.cad.table;

import org.jmouse.cad.document.DocumentKind;
import org.jmouse.cad.document.DocumentModule;
import org.jmouse.cad.document.DocumentNode;
import org.jmouse.cad.document.MetaNode;
import org.jmouse.el.node.Expression;
import org.jmouse.el.parser.Parser;
import org.jmouse.sheet.Sheet;
import org.jmouse.sheet.SheetReader;

import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * 📋 The language of tables: a document of the catalogue whose body is the sheet language's fields and entries — the
 * values a program reads instead of holding them, as an import's filing (whose KiCad's libraries are, which layer is
 * which) or the land patterns footprints are generated by.
 *
 * <pre>
 * table:kicad-libraries("KiCad libraries") {
 *     meta {
 *         summary: "Who holds KiCad's own libraries, their licence, and what each KiCad layer is for."
 *     }
 *     holder "KiCad Libraries Team"
 *     model-scales vrml = 2.54
 *     layers {
 *         F.Cu copper, front
 *     }
 * }
 * </pre>
 *
 * <p>A table is a document like any other — listed, revised, searched, edited as text —; what it is to the engine is the
 * {@link Table} its lines make — the {@link Sheet} a program reads ({@link #sheetOf}), and its lines as a reader sees them.</p>
 */
public final class TableModule implements DocumentModule {

    public static final DocumentKind TABLE = DocumentKind.of("table").drawnBy(TableLinesParser.class);

    @Override
    public List<DocumentKind> kinds() {
        return List.of(TABLE);
    }

    @Override
    public Map<DocumentKind, Function<DocumentNode, Object>> models() {
        return Map.of(TABLE, document -> Table.of(sheetOf(document)));
    }

    @Override
    public List<Parser> getParsers() {
        // The sheet's own parsers stay in the sheet's context: the table's lines parser reads with them there.
        return List.of(new TableLinesParser());
    }

    /**
     * The sheet a table's lines make: its slug and title the document's, its fields and entries the lines of its body —
     * everything but its {@code meta}, which is the catalogue's.
     *
     * @throws IllegalArgumentException for a document that is not a table
     */
    public static Sheet sheetOf(DocumentNode document) {
        if (!document.kind().equals(TABLE)) {
            throw new IllegalArgumentException("'" + document.slug() + "' is a " + document.kind().word() + ", not a table");
        }
        List<Expression> lines = document.getExpressions().stream().filter(line -> !(line instanceof MetaNode)).toList();
        return SheetReader.of(document.slug(), document.title(), lines);
    }
}
