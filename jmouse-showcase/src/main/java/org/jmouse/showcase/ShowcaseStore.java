package org.jmouse.showcase;

import java.sql.SQLException;
import java.util.List;
import java.util.Map;
import org.jmouse.jdbc.JdbcAccess;
import org.jmouse.transaction.DefaultTransactionDefinition;

/** SQL and local transaction boundaries for the showcase. All user values are bound parameters. */
public final class ShowcaseStore {

    public record Entry(long id, String name) {}

    public record Account(long id, String name, long balance) {}

    public record TransferResult(String status, List<Account> before, List<Account> after) {}

    private final JdbcAccess access;

    public ShowcaseStore(JdbcAccess access) throws SQLException {
        this.access = access;
        createSchema();
        seedAccounts();
    }

    public List<Entry> entries() throws SQLException {
        return access
            .jdbc()
            .query("select id, name from showcase_entries order by id desc", (row, index) ->
                new Entry(row.getLong("id"), row.getString("name"))
            );
    }

    public List<Entry> addEntry(String name) throws SQLException {
        access.named().update("insert into showcase_entries(name) values (:name)", Map.of("name", name));
        return entries();
    }

    public List<Account> accounts() throws SQLException {
        return access
            .jdbc()
            .query("select id, name, balance from showcase_accounts order by id", (row, index) ->
                new Account(row.getLong("id"), row.getString("name"), row.getLong("balance"))
            );
    }

    public synchronized TransferResult transfer(
        long sourceId,
        long destinationId,
        long amount,
        boolean forceRollback
    ) throws SQLException {
        if (sourceId == destinationId || amount <= 0) {
            throw new TransferRejectedException("Choose two different accounts and a positive amount");
        }

        List<Account> before = accounts();
        var definition = DefaultTransactionDefinition.builder()
            .name("showcase-transfer")
            .timeoutSeconds(10)
            .build();
        try {
            access.transactions().inTransaction(definition, () -> {
                applyTransfer(sourceId, destinationId, amount, forceRollback);
                return null;
            });
        } catch (DemonstrationRollback expected) {
            return new TransferResult("rolledBack", before, accounts());
        }
        return new TransferResult("committed", before, accounts());
    }

    private void applyTransfer(long sourceId, long destinationId, long amount, boolean forceRollback)
        throws SQLException {
        List<Account> locked = access
            .jdbc()
            .query("select id, name, balance from showcase_accounts order by id for update", (row, index) ->
                new Account(row.getLong("id"), row.getString("name"), row.getLong("balance"))
            );
        Account source = findAccount(locked, sourceId, "Source account not found");
        findAccount(locked, destinationId, "Destination account not found");
        if (source.balance() < amount) {
            throw new TransferRejectedException("Insufficient balance");
        }

        access
            .named()
            .update(
                "update showcase_accounts set balance = balance - :amount where id = :id",
                Map.of("amount", amount, "id", sourceId)
            );
        if (forceRollback) {
            throw new DemonstrationRollback();
        }
        access
            .named()
            .update(
                "update showcase_accounts set balance = balance + :amount where id = :id",
                Map.of("amount", amount, "id", destinationId)
            );
        access.named().update(
            """
            insert into showcase_transfers(from_id, to_id, amount)
            values (:sourceId, :destinationId, :amount)
            """,
            Map.of("sourceId", sourceId, "destinationId", destinationId, "amount", amount)
        );
    }

    private static Account findAccount(List<Account> accounts, long id, String message) {
        return accounts
            .stream()
            .filter(account -> account.id() == id)
            .findFirst()
            .orElseThrow(() -> new TransferRejectedException(message));
    }

    private void createSchema() throws SQLException {
        access.jdbc().update(
            """
            create table if not exists showcase_entries (
                id bigint generated by default as identity primary key,
                name varchar(120) not null
            )
            """
        );
        access.jdbc().update(
            """
            create table if not exists showcase_accounts (
                id bigint primary key,
                name varchar(80) not null,
                balance bigint not null check (balance >= 0)
            )
            """
        );
        access.jdbc().update(
            """
            create table if not exists showcase_transfers (
                id bigint generated by default as identity primary key,
                from_id bigint not null references showcase_accounts(id),
                to_id bigint not null references showcase_accounts(id),
                amount bigint not null check (amount > 0),
                created_at timestamp default current_timestamp
            )
            """
        );
    }

    private void seedAccounts() throws SQLException {
        access.jdbc().update(
            """
            insert into showcase_accounts(id, name, balance)
            select 1, 'Workshop', 10000
            where not exists (select 1 from showcase_accounts where id = 1)
            """
        );
        access.jdbc().update(
            """
            insert into showcase_accounts(id, name, balance)
            select 2, 'Research', 10000
            where not exists (select 1 from showcase_accounts where id = 2)
            """
        );
    }

    static final class TransferRejectedException extends IllegalArgumentException {

        TransferRejectedException(String message) {
            super(message);
        }
    }

    private static final class DemonstrationRollback extends RuntimeException {}
}
